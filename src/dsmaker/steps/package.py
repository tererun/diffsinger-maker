"""Step 7: Package models for OpenUtau."""

from __future__ import annotations

import shutil
import zipfile
from pathlib import Path

import yaml
from rich.console import Console

from dsmaker.config import ProjectConfig
from dsmaker.g2p.base import get_g2p
from dsmaker.utils.platform import ensure_dir

console = Console()


def _generate_character_yaml(config: ProjectConfig) -> dict:
    """Generate OpenUtau character.yaml content."""
    return {
        "name": config.name,
        "singer_type": "diffsinger",
        "author": config.package.author or "dsmaker",
        "version": config.package.version,
        "voice": config.name,
        "web": "",
        "default_phonemizer": _get_phonemizer_id(config.language),
    }


def _get_phonemizer_id(language: str) -> str:
    """Return OpenUtau phonemizer plugin ID for the language."""
    phonemizer_map = {
        "ja": "OpenUtau.Plugin.Builtin.JapanesePhonemizerDiffSinger",
        "en": "OpenUtau.Plugin.Builtin.EnglishPhonemizerDiffSinger",
        "zh": "OpenUtau.Plugin.Builtin.ChinesePhonemizerDiffSinger",
    }
    return phonemizer_map.get(language, "")


def _generate_dsconfig_yaml(config: ProjectConfig, onnx_files: list[str]) -> dict:
    """Generate DiffSinger dsconfig.yaml content."""
    cfg: dict = {
        "phonemes": "phonemes.txt",
        "sample_rate": config.sample_rate,
        "hop_size": 512,
    }

    # Map ONNX files to config keys
    for name in onnx_files:
        if "acoustic" in name:
            cfg["acoustic"] = name
        elif "dur" in name:
            cfg["dur"] = name
        elif "pitch" in name:
            cfg["pitch"] = name
        elif "variance" in name:
            cfg["variance"] = name
        elif "linguistic" in name:
            cfg["linguistic"] = name

    # Vocoder reference
    cfg["vocoder"] = config.export.vocoder

    return cfg


def _generate_phonemes_txt(language: str) -> str:
    """Generate phonemes.txt content for the given language."""
    g2p = get_g2p(language)
    phonemes = sorted(g2p.get_phoneme_set())
    return "\n".join(phonemes)


def run_package(
    project_dir: Path, config: ProjectConfig, make_zip: bool = False
) -> Path:
    """Package trained models into an OpenUtau voice bank."""
    console.print("[bold]Packaging for OpenUtau...[/bold]")

    export_dir = project_dir / "export"
    output_dir = ensure_dir(project_dir / "output" / config.name)

    # Collect ONNX files
    onnx_files = list(export_dir.glob("*.onnx"))
    if not onnx_files:
        console.print("[red]No ONNX files found in export/. Run 'dsmaker export' first.[/red]")
        return output_dir

    # Copy ONNX files
    onnx_names = []
    for onnx in onnx_files:
        dest = output_dir / onnx.name
        shutil.copy2(onnx, dest)
        onnx_names.append(onnx.name)
        console.print(f"  Copied: {onnx.name}")

    # Generate character.yaml
    char_data = _generate_character_yaml(config)
    char_path = output_dir / "character.yaml"
    char_path.write_text(
        yaml.dump(char_data, default_flow_style=False, allow_unicode=True),
        encoding="utf-8",
    )
    console.print("  Generated: character.yaml")

    # Generate dsconfig.yaml
    dscfg_data = _generate_dsconfig_yaml(config, onnx_names)
    dscfg_path = output_dir / "dsconfig.yaml"
    dscfg_path.write_text(
        yaml.dump(dscfg_data, default_flow_style=False, allow_unicode=True),
        encoding="utf-8",
    )
    console.print("  Generated: dsconfig.yaml")

    # Generate phonemes.txt
    phonemes_text = _generate_phonemes_txt(config.language)
    phonemes_path = output_dir / "phonemes.txt"
    phonemes_path.write_text(phonemes_text, encoding="utf-8")
    console.print("  Generated: phonemes.txt")

    # Copy dictionary if available
    dict_src = Path(__file__).parent.parent / "dictionaries" / f"{config.language}.txt"
    if dict_src.exists():
        shutil.copy2(dict_src, output_dir / dict_src.name)
        console.print(f"  Copied: {dict_src.name}")

    # Copy character image if specified
    if config.package.image:
        img_src = project_dir / config.package.image
        if img_src.exists():
            shutil.copy2(img_src, output_dir / img_src.name)

    # Also copy any dsconfig/vocoder YAML generated by DiffSinger export
    for extra in export_dir.glob("*.yaml"):
        shutil.copy2(extra, output_dir / extra.name)

    console.print(f"\n[green]Voice bank ready: {output_dir}[/green]")

    # Create zip if requested
    if make_zip:
        zip_path = project_dir / "output" / f"{config.name}.zip"
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
            for f in output_dir.rglob("*"):
                if f.is_file():
                    zf.write(f, f"{config.name}/{f.relative_to(output_dir)}")
        console.print(f"  Zip: {zip_path} ({zip_path.stat().st_size / 1024 / 1024:.1f} MB)")

    console.print()
    console.print("[bold]To use in OpenUtau:[/bold]")
    console.print(f"  1. Copy [bold]{output_dir}[/bold] to OpenUtau's Singers folder")
    console.print(f"  2. Make sure the vocoder ({config.export.vocoder}) is installed")
    console.print("  3. Select the singer in your project")

    return output_dir
